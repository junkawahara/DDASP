"""Random propositional programs compared with clingo, from fixed seeds.

The first adversarial review checked 1200 random programs by hand once; this
test keeps a seeded stream of such programs in the suite, so that every change
is checked against clingo on programs nobody wrote: choice rules with bounds,
disjunctive heads, constraints, ``not`` / ``not not``, ``#count`` / ``#sum``
bodies with every comparison (gringo rewrites ``!=`` and recursive aggregates
with auxiliary atoms), ``#minimize`` with priorities and negative weights,
``#external`` (of an atom in no rule head: clingo keeps an external free when
clasp's preprocessing removes every rule with it in the head, e.g.
``:- g. e :- g.``, which ddasp follows only for syntactic tautologies; see
docs/DESIGN.md), and ``#show`` of a subset of the atoms or of a term.

``DDASP_RANDOM_PROGRAMS=N`` sets the number of programs (default 500); program
``i`` is generated by ``random.Random(SEED + i)``, so a failure names a program
that can be regenerated with :func:`random_program`.
"""

import os
import random
from collections import Counter

import pytest

ddasp = pytest.importorskip("ddasp")

from conftest import clingo_answer_sets, clingo_optimum  # noqa: E402

SEED = 20261022
N_PROGRAMS = int(os.environ.get("DDASP_RANDOM_PROGRAMS", "500"))

ATOMS = ["a", "b", "c", "d", "e", "f"]
COMPARISONS = [">=", "<=", ">", "<", "=", "!="]


def _literal(rng, atoms):
    atom = rng.choice(atoms)
    return rng.choice([atom, atom, "not " + atom, "not not " + atom])


def _aggregate(rng, atoms):
    elements = rng.sample(atoms, rng.randint(1, min(3, len(atoms))))
    if rng.random() < 0.5:
        body = "#count { " + "; ".join(f"{a} : {_literal(rng, [a])}" for a in elements) + " }"
        bound = rng.randint(0, 3)
    else:
        body = "#sum { " + "; ".join(f"{rng.randint(-3, 3)},{a} : {_literal(rng, [a])}" for a in elements) + " }"
        bound = rng.randint(-3, 4)
    aggregate = f"{body} {rng.choice(COMPARISONS)} {bound}"
    return "not " + aggregate if rng.random() < 0.2 else aggregate


def _body(rng, atoms, min_size=0):
    literals = [_literal(rng, atoms) for _ in range(rng.randint(min_size, 3))]
    if rng.random() < 0.3:
        literals.append(_aggregate(rng, atoms))
    rng.shuffle(literals)
    return ", ".join(literals)


def _rule(rng, atoms, head_atoms):
    kind = rng.choices(["constraint", "normal", "disjunction", "choice"], [2, 4, 2, 3])[0]
    if kind == "constraint":
        return f":- {_body(rng, atoms, min_size=1)}."
    if kind == "normal":
        head = rng.choice(head_atoms)
    elif kind == "disjunction":
        head = " | ".join(rng.sample(head_atoms, rng.randint(2, min(3, len(head_atoms)))))
    else:
        chosen = rng.sample(head_atoms, rng.randint(1, min(3, len(head_atoms))))
        head = "{ " + "; ".join(chosen) + " }"
        if rng.random() < 0.5:
            lower = rng.randint(0, len(chosen))
            upper = rng.randint(lower, len(chosen))
            form = rng.choice(["both", "lower", "upper"])
            if form == "both":
                head = f"{lower} {head} {upper}"
            elif form == "lower":
                head = f"{lower} {head}"
            else:
                head = f"{head} {upper}"
    body = _body(rng, atoms)
    return f"{head} :- {body}." if body else f"{head}."


def _minimize(rng, atoms):
    elements = rng.sample(atoms, rng.randint(1, min(3, len(atoms))))
    priority = rng.randint(0, 2)
    items = [f"{rng.randint(-3, 3)}@{priority},{a} : {_literal(rng, [a])}" for a in elements]
    return "#minimize { " + "; ".join(items) + " }."


def _show(rng, atoms):
    lines = []
    if rng.random() < 0.5:
        shown = atoms
    else:
        shown = [a for a in atoms if rng.random() < 0.5]
        lines.append("#show.")  # hide every atom that is not listed below (also when none is)
    lines += [f"#show {a}/0." for a in shown]
    if rng.random() < 0.25:
        atom = rng.choice(atoms)
        lines.append(f"#show t : {rng.choice([atom, 'not ' + atom])}.")
    return lines


def random_program(rng):
    """One random propositional program (text) drawn from ``rng``."""
    atoms = ATOMS[: rng.randint(3, 6)]
    external = rng.choice(atoms) if rng.random() < 0.15 else None
    head_atoms = [a for a in atoms if a != external]  # an external atom occurs in no head
    lines = [_rule(rng, atoms, head_atoms) for _ in range(rng.randint(1, 6))]
    for _ in range(rng.choices([0, 1, 2], [6, 3, 1])[0]):
        lines.append(_minimize(rng, atoms))
    if external is not None:
        lines.append(f"#external {external}.")
    lines += _show(rng, atoms)
    return "\n".join(lines) + "\n"


def programs():
    """``(index, program text)`` for the N_PROGRAMS seeded programs."""
    for i in range(N_PROGRAMS):
        yield i, random_program(random.Random(SEED + i))


def _family(sets):
    return sorted(sorted(s) for s in sets)


CONFIGS = [(method, project, optimize)
           for method in ("scc", "twocopy") for project in (False, True) for optimize in (False, True)]


@pytest.mark.parametrize("method,project,optimize", CONFIGS,
                         ids=[f"{m}-{'projected' if p else 'all_atoms'}-{'opt' if o else 'all'}" for m, p, o in CONFIGS])
def test_random_programs_match_clingo(tmp_path, method, project, optimize):
    checked = 0
    for i, text in programs():
        if optimize and "#external" in text:
            continue  # the oracle optimizes per assignment of the externals, ddasp over all of them
        path = tmp_path / f"random_{i}.lp"
        path.write_text(text)
        expected = clingo_answer_sets([path], project=project, optimize=optimize)
        res = ddasp.compile_text(text, method=method, project=project, optimize=optimize)
        got = Counter(res.answer_sets())
        if project:
            # Each projected set once; the oracle may list one twice (two assignments of the externals).
            same = set(got) == set(expected) and res.count == len(expected)
        else:
            same = got == expected and res.count == sum(expected.values())
        if same and optimize:
            same = (res.optimum or None) == clingo_optimum([path])
        if not same:
            pytest.fail(f"random program {i} (random.Random({SEED + i})) differs from clingo with "
                        f"method={method} project={project} optimize={optimize}:\n{text}"
                        f"clingo: {_family(expected)}\nddasp:  {_family(got)} (count {res.count}, optimum {res.optimum})")
        checked += 1
    assert checked > 0
